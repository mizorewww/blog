import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { readdir } from 'node:fs/promises'
import path from 'node:path'
import * as lucide from 'lucide-react'

const projectRoot = process.cwd()
const outputPath = path.join(projectRoot, 'lib', 'generated', 'lucide-icons.ts')
const scanRoots = ['app', 'components', 'content', 'lib']
const scanExtensions = new Set(['.js', '.jsx', '.ts', '.tsx', '.md', '.mdx'])
const checkOnly = process.argv.includes('--check')
const reservedIdentifiers = new Set([
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'debugger',
  'default',
  'delete',
  'do',
  'else',
  'export',
  'extends',
  'finally',
  'for',
  'function',
  'if',
  'import',
  'in',
  'instanceof',
  'new',
  'return',
  'super',
  'switch',
  'this',
  'throw',
  'try',
  'typeof',
  'var',
  'void',
  'while',
  'with',
  'yield',
])

function toIconComponentName(value) {
  const key = value
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()

  if (!key) {
    return 'CircleHelp'
  }

  return key
    .split('-')
    .filter(Boolean)
    .map((part) => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('')
}

function readIconAliases() {
  const source = readFileSync(path.join(projectRoot, 'lib', 'iconAliases.ts'), 'utf8')
  const aliases = new Map()

  for (const match of source.matchAll(/['"]([^'"]+)['"]:\s*['"]([A-Za-z][A-Za-z0-9]*)['"]/g)) {
    aliases.set(match[1], match[2])
  }

  for (const match of source.matchAll(
    /\b([A-Za-z][A-Za-z0-9]*)\s*:\s*['"]([A-Za-z][A-Za-z0-9]*)['"]/g
  )) {
    aliases.set(match[1], match[2])
  }

  return aliases
}

function normalizeIconName(value, aliases) {
  const key = value
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s_]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase()

  return aliases.get(key) || toIconComponentName(value)
}

function addIcon(iconNames, rawName, aliases) {
  const iconName = normalizeIconName(rawName, aliases)

  if (lucide[iconName]) {
    iconNames.add(iconName)
  }
}

async function collectFiles(root) {
  const directory = path.join(projectRoot, root)

  if (!existsSync(directory)) {
    return []
  }

  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name)

    if (entry.isDirectory()) {
      files.push(...(await collectFiles(path.relative(projectRoot, entryPath))))
      continue
    }

    if (entry.isFile() && scanExtensions.has(path.extname(entry.name))) {
      files.push(entryPath)
    }
  }

  return files
}

function collectIconsFromSource(source, iconNames, aliases) {
  for (const match of source.matchAll(/:icon-([A-Za-z0-9_-]+):/g)) {
    addIcon(iconNames, match[1], aliases)
  }

  for (const match of source.matchAll(/<Icon\b[^>]*\bname=["']([^"']+)["']/g)) {
    addIcon(iconNames, match[1], aliases)
  }

  for (const match of source.matchAll(/\bname=\{["']([^"']+)["']\}/g)) {
    addIcon(iconNames, match[1], aliases)
  }

  for (const block of source.matchAll(/\b(?:metaIconNames|iconNames)\b[\s\S]*?\}/g)) {
    for (const match of block[0].matchAll(/:\s*["']([A-Z][A-Za-z0-9]+)["']/g)) {
      addIcon(iconNames, match[1], aliases)
    }
  }
}

function safeImportName(iconName) {
  if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(iconName) && !reservedIdentifiers.has(iconName)) {
    return iconName
  }

  return `${iconName}Icon`
}

function generateSource(iconNames) {
  const sortedIconNames = [...iconNames].sort((a, b) => a.localeCompare(b))
  const imports = sortedIconNames
    .map((iconName) => {
      const importName = safeImportName(iconName)
      return importName === iconName ? `  ${iconName},` : `  ${iconName} as ${importName},`
    })
    .join('\n')
  const registry = sortedIconNames
    .map((iconName) => {
      const importName = safeImportName(iconName)
      return importName === iconName ? `  ${iconName},` : `  ${iconName}: ${importName},`
    })
    .join('\n')

  return `// Generated by scripts/generate-lucide-icons.mjs. Do not edit by hand.
import {
${imports}
  type LucideIcon,
} from 'lucide-react'

export const generatedLucideIcons: Record<string, LucideIcon> = {
${registry}
}
`
}

const aliases = readIconAliases()
const iconNames = new Set(['CircleHelp'])

for (const iconName of aliases.values()) {
  addIcon(iconNames, iconName, aliases)
}

for (const root of scanRoots) {
  for (const file of await collectFiles(root)) {
    collectIconsFromSource(readFileSync(file, 'utf8'), iconNames, aliases)
  }
}

const nextSource = generateSource(iconNames)
const currentSource = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : ''

if (checkOnly) {
  if (currentSource !== nextSource) {
    console.error('Generated lucide icon registry is out of date. Run `yarn icons:generate`.')
    process.exit(1)
  }

  console.log('Generated lucide icon registry is up to date')
} else {
  writeFileSync(outputPath, nextSource)
  console.log(`Generated ${iconNames.size} lucide icon imports`)
}
